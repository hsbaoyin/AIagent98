# Generates src/gui/emoji_table.h from the AIagent98 Emoji Pack mapping.
#
# The pack itself stays out of the repository (.gitignore): the generated
# table is what the GUI needs, because Win9x has no color emoji font and the
# transcript has to turn emoji it receives into text it can actually draw.
#
# Run from the repository root:  powershell -File tools/gen_emoji_table.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$pack = 'AIagent98-Emoji-Pack-v2.0'
$csvPath = Join-Path $pack 'mapping\emoji.csv'
$outPath = 'src\gui\emoji_table.h'
if (-not (Test-Path $csvPath)) {
    throw ("missing mapping file: {0} (pass the pack next to the repository)" -f $csvPath)
}

$rows = Import-Csv -Path $csvPath -Encoding UTF8
$used = @{}
$entries = New-Object System.Collections.Generic.List[object]

foreach ($r in $rows) {
    $cp = [Convert]::ToInt32($r.codepoint, 16)
    # English name -> :shortcode:, de-duplicated so expand() is unambiguous.
    $slug = $r.name_en.ToLower() -replace '[^a-z0-9]+', '_'
    $slug = $slug.Trim('_')
    if ([string]::IsNullOrEmpty($slug)) { $slug = 'emoji' }
    if ($slug -match '^[0-9]') { $slug = 'e' + $slug }
    $base = $slug
    $n = 2
    while ($used.ContainsKey($slug)) {
        $slug = ('{0}_{1}' -f $base, $n)
        $n++
    }
    $used[$slug] = $true
    $entries.Add([pscustomobject]@{ Cp = $cp; Id = $r.id; Slug = $slug })
}

# Sorted by code point so emoji.c can binary search.
$sorted = $entries | Sort-Object -Property Cp

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('/* Generated by tools/gen_emoji_table.ps1 - do not edit by hand.')
$lines.Add(' *')
$lines.Add(' * Source: AIagent98 Emoji Pack v2.0, mapping/emoji.csv')
$lines.Add(' * Artwork derives from Noto Color Emoji (SIL OFL 1.1); keep the')
$lines.Add(" * pack's LICENSE-NOTO.txt alongside the BMP assets.")
$lines.Add(' */')
$lines.Add('#ifndef A98_EMOJI_TABLE_H')
$lines.Add('#define A98_EMOJI_TABLE_H')
$lines.Add('')
$lines.Add(('#define A98_EMOJI_PACK_COUNT {0}' -f $sorted.Count))
$lines.Add('')
$lines.Add('static const A98EmojiEntry g_a98_emoji_pack[A98_EMOJI_PACK_COUNT] = {')
foreach ($e in $sorted) {
    $lines.Add(('    {{ 0x{0:X5}UL, "{1}", "{2}" }},' -f $e.Cp, $e.Id, $e.Slug))
}
$lines.Add('};')
$lines.Add('')
$lines.Add('#endif /* A98_EMOJI_TABLE_H */')

[System.IO.File]::WriteAllText((Join-Path $root $outPath),
                               (($lines -join "`r`n") + "`r`n"),
                               [System.Text.Encoding]::ASCII)
Write-Host ('wrote {0} ({1} entries)' -f $outPath, $sorted.Count)
